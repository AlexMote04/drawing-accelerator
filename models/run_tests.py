import subprocess
import os
import sys

# --- Configuration ---
CONTROLLER_EXE = "./controller" # Path to C++ Golden Model
VSDUMP_PATH = "vsDump.txt"              # C++ model output file
VERILOG_SIM_EXE = "vsim"                # Or "./simv" for VCS
SIM_ARGS = ["-c", "-do", "run -all; quit"] # Arguments for Questa

FS_WIDTH = 640
FS_HEIGHT = 480

def run_command_cpp(test_name: str, command: str):
    """Runs the cpp model to generate golden reference data."""
    print(f"--- Generating Golden Data for: {test_name} ---")
    try:
        subprocess.run(CONTROLLER_EXE, input=command, text=True, check=True)
    except subprocess.CalledProcessError as e:
        print(f"Error running C++ model: {e}")
        sys.exit(1)
    except FileNotFoundError:
        print(f"Error: C++ executable not found at {CONTROLLER_EXE}")
        sys.exit(1)

def read_vsdump():
    """Loads the vsDump.txt file generated by the cpp model."""
    if not os.path.exists(VSDUMP_PATH):
        return []

    with open(VSDUMP_PATH, mode='r', encoding='utf-8') as f:
        return [line.strip() for line in f if line.strip()]

def convert_golden_data_sv(golden_data_cpp: list[str]):
    """
    Converts C++ pixel output (x, y, colour) into 
    SystemVerilog Memory format (Address, ByteLane, DataWord).
    """
    golden_data_sv = []
    for pixel_value_cpp in golden_data_cpp:
        parts = pixel_value_cpp.split()
        if len(parts) < 3:
            continue

        x, y, colour = map(int, parts)

        # Calculate Linear Address
        byte_addr = x + (FS_WIDTH * y)
        word_addr = byte_addr // 4
        byte_pos = byte_addr % 4 # 0, 1, 2, or 3

        # Calculate Active Low Byte Enable (nbyte)
        # e.g., pos 0 -> 1110 (0xE), pos 1 -> 1101 (0xD)
        nbyte = ~(1 << byte_pos) & 0xF

        # Calculate Data Word (Little Endian Shift)
        data = colour << (byte_pos * 8)

        # Format: <Word Address> <NByte> <32-bit Data>
        golden_data_sv.append(f"{word_addr} {nbyte} {data}")

    return golden_data_sv

def run_simulation(test_name, command_str, golden_data_list):
    """
    Writes temp files and runs the Verilog simulation as a subprocess.
    """
    cmd_file = f"{test_name}_cmd.dat"
    gold_file = f"{test_name}_gold.dat"

    # 1. Write the Command file for the SV Testbench
    with open(cmd_file, "w", encoding='utf-8') as f:
        f.write(command_str)

    # 2. Write the Golden Data file for the SV Testbench
    with open(gold_file, "w", encoding='utf-8') as f:
        f.write("\n".join(golden_data_list))

    # 3. Construct Simulator Arguments
    # Passes file names via +plusargs
    sim_cmd = [VERILOG_SIM_EXE] + SIM_ARGS + [
        "unit_Testbench", # Top level module name
        f"+command_file={cmd_file}",
        f"+golden_file={gold_file}"
    ]

    print(f"--- Running Simulation: {test_name} ---")
    try:
        # Capture stdout to check for "TEST PASSED"
        result = subprocess.run(sim_cmd, capture_output=True, text=True, check=True)

        # check for success message from Testbench
        if "TEST PASSED" in result.stdout:
            print(f"✅ {test_name}: PASSED")
        else:
            print(f"❌ {test_name}: FAILED")
            print("Simulation Output Snippet:")
            print("\n".join(result.stdout.splitlines()[-10:])) # Last 10 lines

    except subprocess.CalledProcessError as e:
        print(f"❌ Simulation Crashed for {test_name}")
        print(e.stderr)
    finally:
        # Optional: Clean up temp files
        if os.path.exists(cmd_file):
            os.remove(cmd_file)
        if os.path.exists(gold_file):
            os.remove(gold_file)

def run_test(test_name, command):
    # 1. Run C++ Model
    run_command_cpp(test_name, command)

    # 2. Process Data
    golden_data_cpp = read_vsdump()
    golden_data_sv = convert_golden_data_sv(golden_data_cpp)

    # 3. Run Verilog Simulation
    run_simulation(test_name, command, golden_data_sv)

if __name__ == "__main__":
    # List of tests: (Name, Command String)
    tests_to_run = [
        ("test_simple_line",     "line 10 10 15 12 0x99"),
        ("test_horizontal_line", "line 20 20 25 20 0xAA"),
        ("test_vertical_line",   "line 30 30 30 35 0xBB"),
        ("test_single_pixel",    "line 40 40 40 40 0xCC"),
        ("test_reverse_line",    "line 50 50 45 45 0xDD")
    ]

    for test in tests_to_run:
        run_test(test[0], test[1])
